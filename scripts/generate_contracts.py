"""Generate TypeScript, Python, Rust and Go bindings from one contract schema.

Run after editing ``packages/contracts/schemas.json``::

    python scripts/generate_contracts.py
    python scripts/generate_contracts.py --check

``--check`` fails when generated files are stale, so CI catches a schema change
that was not propagated to all four languages.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "packages" / "contracts"
SCHEMA = CONTRACTS / "schemas.json"
HEADER = "Generated by scripts/generate_contracts.py from packages/contracts/schemas.json. Do not edit."


def load() -> dict:
    data = json.loads(SCHEMA.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1:
        raise ValueError("Unsupported schema_version")
    return data


def py_type(schema: dict) -> str:
    kind = schema.get("type")
    if kind == "array":
        return "list[" + py_type(schema.get("items", {})) + "]"
    if kind == "object":
        return "dict[str, Any]"
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    if kind == "boolean":
        return "bool"
    return "str"


def ts_type(schema: dict) -> str:
    kind = schema.get("type")
    if kind == "array":
        return ts_type(schema.get("items", {})) + "[]"
    if kind == "object":
        return "Record<string, unknown>"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    return "string"


def rust_type(schema: dict, optional: bool) -> str:
    kind = schema.get("type")
    if kind == "array":
        base = "Vec<" + rust_type(schema.get("items", {}), False) + ">"
    elif kind == "object":
        base = "serde_json::Value"
    elif kind == "integer":
        base = "i64"
    elif kind == "number":
        base = "f64"
    elif kind == "boolean":
        base = "bool"
    else:
        base = "String"
    return f"Option<{base}>" if optional else base


def go_type(schema: dict, optional: bool) -> str:
    kind = schema.get("type")
    if kind == "array":
        return "[]" + go_type(schema.get("items", {}), False)
    if kind == "object":
        return "map[string]any"
    if kind == "integer":
        base = "int64"
    elif kind == "number":
        base = "float64"
    elif kind == "boolean":
        base = "bool"
    else:
        base = "string"
    return "*" + base if optional else base


GO_INITIALISMS = {
    "id": "ID", "sha256": "SHA256", "url": "URL", "api": "API",
    "http": "HTTP", "json": "JSON", "sql": "SQL", "uuid": "UUID",
}


def go_name(field: str) -> str:
    parts = field.split("_")
    words = []
    for part in parts:
        words.append(GO_INITIALISMS.get(part, part[:1].upper() + part[1:]))
    name = "".join(words)
    return "ID" if name == "Id" else name


def python_bindings(data: dict) -> str:
    lines = [
        f'"""{HEADER}"""',
        "",
        "from typing import Any, Literal, NotRequired, TypedDict",
        "",
        f"SCHEMA_VERSION = {data['schema_version']}",
        "",
    ]
    for name in sorted(data["$defs"]):
        schema = data["$defs"][name]
        required = set(schema.get("required", []))
        lines.append(f"class {name}(TypedDict):")
        lines.append(f'    """{name} contract."""')
        lines.append("")
        for field, spec in schema.get("properties", {}).items():
            annotation = py_type(spec)
            if spec.get("const") is not None:
                annotation = f"Literal[{json.dumps(spec['const'])}]"
            elif spec.get("enum"):
                annotation = "Literal[" + ", ".join(json.dumps(value) for value in spec["enum"]) + "]"
            if field not in required:
                annotation = f"NotRequired[{annotation}]"
            lines.append(f"    {field}: {annotation}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def typescript_bindings(data: dict) -> str:
    lines = [
        f"// {HEADER}",
        "",
        f"export const SCHEMA_VERSION = {data['schema_version']} as const;",
        "",
    ]
    for name in sorted(data["$defs"]):
        schema = data["$defs"][name]
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for field, spec in schema.get("properties", {}).items():
            annotation = ts_type(spec)
            if spec.get("const") is not None:
                annotation = json.dumps(spec["const"])
            elif spec.get("enum"):
                annotation = " | ".join(json.dumps(value) for value in spec["enum"])
            optional = "?" if field not in required else ""
            lines.append(f"  {field}{optional}: {annotation};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def rust_bindings(data: dict) -> str:
    lines = [
        f"// {HEADER}",
        "#![allow(dead_code)]",
        "use serde::{Deserialize, Serialize};",
        "",
        f"pub const SCHEMA_VERSION: i64 = {data['schema_version']};",
        "",
    ]
    for name in sorted(data["$defs"]):
        schema = data["$defs"][name]
        required = set(schema.get("required", []))
        lines.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
        lines.append(f"pub struct {name} {{")
        for field, spec in schema.get("properties", {}).items():
            optional = field not in required
            annotation = rust_type(spec, optional)
            if optional:
                lines.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
            lines.append(f"    pub {field}: {annotation},")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def go_bindings(data: dict) -> str:
    lines = [
        f"// {HEADER}",
        "package contracts",
        "",
        f"const SchemaVersion = {data['schema_version']}",
        "",
    ]
    for name in sorted(data["$defs"]):
        schema = data["$defs"][name]
        required = set(schema.get("required", []))
        lines.append(f"type {name} struct {{")
        for field, spec in schema.get("properties", {}).items():
            optional = field not in required
            annotation = go_type(spec, optional)
            tag = field + (",omitempty" if optional else "")
            lines.append(f'\t{go_name(field)} {annotation} `json:"{tag}"`')
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


GENERATORS = {
    Path("python/contracts.py"): python_bindings,
    Path("typescript/index.ts"): typescript_bindings,
    Path("rust/contracts.rs"): rust_bindings,
    Path("go/contracts.go"): go_bindings,
}


def expected_files(data: dict) -> dict[Path, str]:
    return {path: generate(data) for path, generate in GENERATORS.items()}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args(argv)
    try:
        data = load()
        outputs = expected_files(data)
    except (OSError, ValueError, KeyError) as exc:
        print(f"Contract error: {exc}", file=sys.stderr)
        return 1
    stale = []
    for relative, content in outputs.items():
        target = CONTRACTS / relative
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    if args.check:
        if stale:
            print("Stale generated contracts: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("Generated contracts are up to date")
        return 0
    print(f"Generated {len(outputs)} contract bindings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
