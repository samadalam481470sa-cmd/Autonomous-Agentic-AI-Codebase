"""Bounded multi-file AI planning and atomic approved patch application.

Proposals are generated by a configured model, but NEVER written until the
administrator explicitly approves the exact proposal SHA-256 digest.
"""
import asyncio
import difflib
import hashlib
import json
import os
import re
import tempfile
import uuid
from pathlib import Path

import httpx
from fastapi import APIRouter, Header, HTTPException
from pydantic import BaseModel, Field
from .studio import authorize, current, digest, resolve, WRITE_LOCK
from . import checkpoints, turns
from .engine import workspace
from .code_agent import config, strip_fence

router=APIRouter(prefix="/api/agent/batch",tags=["multi-file-agent"])
MAX_FILES=8
MAX_BYTES=120_000

class BatchRequest(BaseModel):
    project:str=Field(pattern=r"^[A-Za-z0-9_-]{1,64}$")
    instruction:str=Field(min_length=4,max_length=4000)
    paths:list[str]=Field(min_length=1,max_length=MAX_FILES)
    model:str|None=Field(default=None,max_length=120)

class ApplyRequest(BaseModel):
    project:str=Field(pattern=r"^[A-Za-z0-9_-]{1,64}$")
    proposal_id:str=Field(pattern=r"^[a-f0-9]{32}$")
    proposal_hash:str=Field(pattern=r"^[a-f0-9]{64}$")

def store_path(project,proposal_id):
    return workspace(project)/".agent"/"proposals"/(proposal_id+".json")

def proposals_hash(changes):
    canonical=json.dumps(changes,sort_keys=True,ensure_ascii=False,separators=(",",":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()

def check_paths(project,paths):
    if len(set(paths))!=len(paths):
        raise HTTPException(400,"Duplicate file paths")
    validated=[]
    for name in paths:
        if not isinstance(name,str) or len(name)>512 or not name or name.startswith("/"):
            raise HTTPException(400,"Invalid path")
        target=resolve(project,name)
        if target.is_symlink():
            raise HTTPException(403,"Symlinks are not supported")
        previous=current(target)
        if len(previous.encode("utf-8"))>MAX_BYTES:
            raise HTTPException(413,"File too large for a single batch")
        validated.append((name,target,previous))
    return validated

async def generate_text(client,base,model,key,prompt):
    response=await client.post(base+"/chat/completions",
        headers={"Authorization":"Bearer "+key},
        json={"model":model,"messages":[
            {"role":"system","content":"Return ONLY complete source text for the given ONE file. No markdown, no explanations. Keep unrelated code unchanged. Never claim tests were run."},
            {"role":"user","content":prompt}],
            "temperature":0.1,"max_tokens":4096})
    response.raise_for_status()
    content=response.json()["choices"][0]["message"]["content"]
    if not isinstance(content,str):
        raise ValueError("Non-text model response")
    return strip_fence(content)

def create_record(project,changes):
    record_id=uuid.uuid4().hex
    proposal_hash=proposals_hash(changes)
    path=store_path(project,record_id)
    path.parent.mkdir(parents=True,exist_ok=True)
    record={"id":record_id,"hash":proposal_hash,"status":"pending","changes":changes}
    with path.open("x",encoding="utf-8") as handle:
        json.dump(record,handle,ensure_ascii=False)
    return {"proposal_id":record_id,"proposal_hash":proposal_hash,"changes":[
        {"path":c["path"],"diff":c["diff"],"expected_sha256":c["expected_sha256"],
         "proposed_sha256":digest(c["content"])} for c in changes],
        "requires_approval":True}

@router.post("/propose")
async def propose_batch(body:BatchRequest,authorization:str|None=Header(default=None)):
    authorize(authorization)
    files=check_paths(body.project,body.paths)
    base,model,key=config(body.model) if body.model else config()
    changes=[]
    try:
        async with httpx.AsyncClient(timeout=180,follow_redirects=False,trust_env=False) as client:
            for name,_,old in files:
                prompt=f"Task: {body.instruction}\nFile: {name}\nExisting source:\n{old[:80000]}"
                output=await generate_text(client,base,model,key,prompt)
                if not output or len(output.encode("utf-8"))>MAX_BYTES:
                    raise ValueError("Generated file is empty or too large")
                diff="".join(difflib.unified_diff(old.splitlines(keepends=True),
                    output.splitlines(keepends=True),fromfile="current/"+name,tofile="proposed/"+name))
                changes.append({"path":name,"expected_sha256":digest(old),"content":output,"diff":diff})
    except (httpx.HTTPError,ValueError,KeyError,IndexError,TypeError):
        raise HTTPException(502,"One or more model proposals failed; no files were changed")
    return create_record(body.project,changes)

def apply_record(project,proposal_id,proposal_hash):
    with WRITE_LOCK:
        return _apply_record_locked(project,proposal_id,proposal_hash)

def _apply_record_locked(project,proposal_id,proposal_hash):
    source=store_path(project,proposal_id)
    if not source.is_file():
        raise HTTPException(404,"Proposal not found")
    record=json.loads(source.read_text(encoding="utf-8"))
    if record["status"]!="pending" or record["hash"]!=proposal_hash or proposals_hash(record["changes"])!=proposal_hash:
        raise HTTPException(409,"Proposal is no longer pending or its hash differs")
    changes=record["changes"]
    files=check_paths(project,[c["path"] for c in changes])
    for (name,_,old),c in zip(files,changes):
        if digest(old)!=c["expected_sha256"]:
            raise HTTPException(409,"Source changed since proposal: "+name)
    # Save pre-apply snapshots before changing any source file. Each restore
    # checks the corresponding applied digest, so stale snapshots cannot
    # overwrite later work without explicit review.
    checkpoint_ids=[]
    for (name,target,old),c in zip(files,changes):
        checkpoint_ids.append(checkpoints.snapshot(
            project,name,old,target.is_file(),c["content"]
        ))
    # Write replacement files to sibling staging files first. Roll back on errors.
    staged=[]
    originals={str(path):(old,path.exists()) for _,path,old in files}
    applied=[]
    try:
        for c,(_,target,_) in zip(changes,files):
            target.parent.mkdir(parents=True,exist_ok=True)
            with tempfile.NamedTemporaryFile(mode="w",encoding="utf-8",dir=target.parent,
                    prefix=".agent-staging-",delete=False) as temporary:
                temporary.write(c["content"])
                staged.append((Path(temporary.name),target))
        for temporary,target in staged:
            os.replace(temporary,target)
            applied.append(target)
        record["status"]="applied"
        source.write_text(json.dumps(record,ensure_ascii=False),encoding="utf-8")
    except OSError:
        for target in reversed(applied):
            old,existed=originals[str(target)]
            if not existed:
                target.unlink(missing_ok=True)
            else:
                target.write_text(old,encoding="utf-8")
        raise HTTPException(500,"Failed to apply batch; rollback attempted")
    finally:
        for temporary,_ in staged:
            temporary.unlink(missing_ok=True)
    turn_id=turns.new_turn()
    for change,checkpoint_id in zip(changes,checkpoint_ids):
        turns.record(project,turn_id,change["path"],checkpoint_id)
    return {"applied":len(applied),"paths":[c["path"] for c in changes],
            "proposal_id":proposal_id,"checkpoint_ids":checkpoint_ids,
            "turn_id":turn_id}

@router.post("/apply")
def apply_batch(body:ApplyRequest,authorization:str|None=Header(default=None),
                x_confirm_change:str|None=Header(default=None)):
    authorize(authorization)
    if x_confirm_change!="approve":
        raise HTTPException(428,"Explicit human approval required")
    return apply_record(body.project,body.proposal_id,body.proposal_hash)
